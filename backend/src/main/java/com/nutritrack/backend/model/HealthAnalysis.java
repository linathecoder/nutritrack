package com.nutritrack.backend.model;

import jakarta.persistence.*;
import lombok.Getter;
import lombok.Setter;
import lombok.NoArgsConstructor;

import java.time.Instant;

/**
 * Cached result of the AI health analysis for a given barcode.
 * One row per barcode – Gemini is never called twice for the same product.
 */
@Entity
@Table(name = "health_analyses")
@Getter
@Setter
@NoArgsConstructor
public class HealthAnalysis {

    /** Barcode of the analysed product (same PK as FoodProduct). */
    @Id
    private String barcode;

    /** Deterministic score 0-100 computed in Java (never by AI). */
    private int score;

    /** Human-readable rating: Excellent / Good / Fair / Poor. */
    private String rating;

    /** Short plain-language explanation written by Gemini (or fallback). */
    @Column(length = 2000)
    private String explanation;

    /** One meal pairing suggestion from Gemini (or fallback). */
    @Column(length = 2000)
    private String pairingSuggestion;

    /** Always set by backend code – never generated by AI (BR-09). */
    @Column(nullable = false, length = 500)
    private String disclaimer;

    /** UTC timestamp of when the analysis was first computed. */
    private Instant generatedAt;
}
